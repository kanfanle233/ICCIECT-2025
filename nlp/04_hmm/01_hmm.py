"""
隐马尔可夫模型（HMM）暴力枚举示例。

教学重点：通过暴力枚举所有可能的隐藏状态路径，
计算条件概率 P(连续三天都爱 | 第1天热情, 第2天未知, 第3天热情)。
帮助理解 HMM 的联合概率计算和贝叶斯公式应用。
"""

import numpy as np

# --- 1. 初始化矩阵（你提供的数据） ---
# 隐藏状态：0=爱，1=状态1，2=状态2
# 观测状态：0=热情，1=不热情
pi = np.array([0.8, 0.1, 0.1])  # 初始状态概率（第一天大概率是爱的）

A = np.array([  # 状态转移概率矩阵 (3x3)
    [0.9, 0.0, 0.1],  # 爱 -> 爱的概率高达 0.9
    [0.2, 0.7, 0.1],
    [0.1, 0.5, 0.4]
])

B = np.array([  # 观测发射概率矩阵 (3x2)
    [0.9, 0.1],  # 如果爱你，表现出热情的概率高达 0.9
    [0.2, 0.8],
    [0.5, 0.5]
])

# 2. 暴力枚举：计算连续三天所有 3x3x3=27 种路径的联合概率
ps = []
target_joint_prob = 0  # 专门用来存分子：连续三天都爱你的联合概率

for X1 in range(3):
    for X2 in range(3):
        for X3 in range(3):
            # 已知的观测证据
            Y1 = 0  # 第一天热情
            Y3 = 0  # 第三天热情

            # 核心公式：P(X1,X2,X3, Y1,Y3)
            # 注意！因为 Y2 未知，所以不需要乘以 B[X2, Y2]，它自己求和抵消为 1 了。
            p = pi[X1] * B[X1, Y1] * A[X1, X2] * A[X2, X3] * B[X3, Y3]

            ps.append(p)

            # 如果这条路径正好是“连续三天爱”（即 X1=0, X2=0, X3=0）
            if X1 == 0 and X2 == 0 and X3 == 0:
                target_joint_prob = p

# 3. 计算最终的条件概率 P(X1=0, X2=0, X3=0 | Y1=0, Y2=?, Y3=0)
# 根据贝叶斯公式，分母是所有可能路径下产生“第1天热情、第3天热情”的总概率
total_prob_Y = np.sum(ps)

# 分子除以分母
final_prob = target_joint_prob / total_prob_Y

print(f"【分子】连续三天爱你，且表现出1、3天热情的联合概率: {target_joint_prob:.5f}")
print(f"【分母】无论爱不爱，只要第1、3天表现出热情的总概率: {total_prob_Y:.5f}")
print("-" * 50)
print(f"最终预测结果 P(三天都爱 | 第1天热情, 第2天未知, 第3天热情) = {final_prob:.2%}")