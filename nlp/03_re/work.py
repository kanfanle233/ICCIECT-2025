"""
正则表达式匹配二进制数（带分组捕获）。

教学重点：使用 re.match 的分组功能提取匹配结果中的子串，
并通过 \\w \\W \\d 等预定义字符集的注释加深理解。
"""

import re

# --- 1. 定义正则模式 ---
# 匹配以 0b 开头的二进制数，括号捕获有效数字部分
p = r"0b0*(0|1[01]+)"

# --- 2. 测试多个二进制字符串 ---
for s in ('0b0', '0b101', '0b10111', '0b00001011', '0b10000000000'):
    m = re.match(p, s)
    if m is None:
        print("not match")
    else:
        print(m.group(1))   # group(1) 输出捕获组中的内容

# --- 3. 常用预定义字符集速查 ---
# \w  ===   [0-9a-zA-Z_]
# \W  ===   [^0-9a-zA-Z_]
# \d  ===   [0-9]
