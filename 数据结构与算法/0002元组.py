"""
元组（Tuple）的基本操作示例。

教学重点：演示元组的创建、索引、切片和删除操作。
元组是不可变的有序序列，与列表类似但元素不可修改。
"""

# --- 1. 创建元组 ---
tup1 = ('physics', 'chemistry', 1997, 2000);   # 混合类型元组
tup2 = (1, 2, 3, 4, 5, 6, 7 );                 # 整数元组

# --- 2. 索引和切片 ---
print ("tup1[0]: ", tup1[0])       # 输出: physics（第一个元素，索引从 0 开始）
print ("tup2[1:5]: ", tup2[1:5])   # 输出: (2, 3, 4, 5)（切片：左闭右开）

# --- 3. 删除元组 ---
tup3= ('physics', 'chemistry', 1997, 2000);
print (tup3);          # 输出元组内容
del tup3;              # 删除整个元组对象（注意：不能删除元组中的单个元素）
print ("After deleting tup : ");
print (tup3);          # 此行会报错 NameError，因为 tup3 已被删除