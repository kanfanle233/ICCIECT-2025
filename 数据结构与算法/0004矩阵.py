"""
矩阵（Matrix）的基本操作示例。

教学重点：演示使用 NumPy 创建矩阵、索引访问元素、
以及使用 append 在矩阵末尾追加行。
矩阵格式：每行 = [星期, 值1, 值2, 值3, 值4]。
"""

from numpy import *

# --- 1. 创建矩阵 ---
# 每行代表一天的数据：[星期名, 数值1, 数值2, 数值3, 数值4]
m = array([['Mon', 18, 20, 22, 17], ['Tue', 11, 18, 21, 18],
           ['Wed', 15, 21, 20, 19], ['Thu', 11, 20, 22, 21],
           ['Fri', 18, 17, 23, 22], ['Sat', 12, 22, 20, 18],
           ['Sun', 13, 15, 19, 16]])

# --- 2. 索引访问 ---
# Print data for Wednesday
print(m[2])         # 输出 Wed 行：['Wed' 15 21 20 19]（第 3 行，索引为 2）

# Print data for friday evening
print(m[4][3])      # 输出 Fri 行第 4 列：23（索引 [行][列]）


# --- 3. 矩阵追加行 ---
from numpy import *
m1 = array([['Mon',18,20,22,17],['Tue',11,18,21,18],
   ['Wed',15,21,20,19],['Thu',11,20,22,21],
   ['Fri',18,17,23,22],['Sat',12,22,20,18],
   ['Sun',13,15,19,16]])

# append 的第三个参数 0 表示沿行方向（纵向）追加
m_r = append(m1,[['Avg',12,15,13,11]],0)

print(m_r)          # 输出追加了平均值行后的完整矩阵