"""
二维数组的基本操作示例。

教学重点：演示 Python 中用嵌套列表模拟二维数组，
包括创建、修改元素、遍历等操作。
"""

from array import *

# --- 1. 创建二维数组（嵌套列表） ---
# 注意：各行长度可以不同（不规则数组/锯齿数组）
T = [[11, 12, 5, 2], [15, 6,10], [10, 8, 12, 5], [12,15,8,6]]

# --- 2. 修改数组内容 ---
T[2] = [11,9]    # 将第 3 行整体替换为 [11, 9]（行级别赋值）
T[0][3] = 7      # 将第 1 行第 4 列的元素修改为 7（元素级别赋值）

# --- 3. 遍历二维数组 ---
for r in T:          # 遍历每一行
   for c in r:       # 遍历行中的每个元素
      print(c,end = " ")
   print()           # 每行结束后换行